#!/usr/bin/env bash
set -euo pipefail

SKILLBOOK="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
CLAUDE_HOME="${CLAUDE_HOME:-$HOME/.claude}"
CODEX_HOME="${CODEX_HOME:-$HOME/.codex}"
source "$SKILLBOOK/scripts/codex-agent-config.sh"

PROBLEMS=0
SYNCED_SKILLS_DIR="synced"

known_project_key() {
  local key="$1" projects_root="${PROJECTS_ROOT:-$HOME/Projects}"

  [ -d "$projects_root/$key" ] && return 0
  grep -oE 'echo [A-Za-z0-9_-]+ ;;' "$SKILLBOOK/hooks/scope-map.sh" | awk '{print $2}' | grep -qx -- "$key"
}

note_problem() {
  local section="$1" msg="$2"
  PROBLEMS=$((PROBLEMS + 1))
  echo "FAIL $section: $msg"
}

FM_ERROR=""
FM_SECOND_DASH=""
read_frontmatter() {
  local file="$1"
  local -n fm_out="$2"
  FM_ERROR=""
  FM_SECOND_DASH=""
  fm_out=""
  if [ ! -f "$file" ]; then
    FM_ERROR="file missing"
    return 1
  fi
  local first_line
  first_line=$(sed -n '1p' "$file")
  if [ "$first_line" != "---" ]; then
    FM_ERROR="frontmatter does not open with ---"
    return 1
  fi
  local second_dash
  second_dash=$(awk 'NR>1 && $0=="---" {print NR; exit}' "$file")
  if [ -z "$second_dash" ]; then
    FM_ERROR="frontmatter has no closing ---"
    return 1
  fi
  FM_SECOND_DASH="$second_dash"
  # shellcheck disable=SC2034  # fm_out is a nameref (local -n above), written through to the caller
  fm_out=$(sed -n "2,$((second_dash - 1))p" "$file")
  return 0
}

fm_count() {
  local fm="$1" key="$2"
  printf '%s\n' "$fm" | grep -c "^${key}:" || true
}

fm_value() {
  local fm="$1" key="$2"
  printf '%s\n' "$fm" | sed -n "/^${key}:/s/^${key}:[[:space:]]*//p"
}

fm_block() {
  local fm="$1" key="$2"
  printf '%s\n' "$fm" | awk -v key="^${key}:" '
    $0 ~ key { inblock = 1 }
    inblock && $0 !~ key && /^[A-Za-z_-]+:/ { exit }
    inblock { print }
  '
}

check_name_field() {
  local section="$1" file="$2" fm="$3" expected="$4"
  local count
  count=$(fm_count "$fm" name)
  if [ "$count" -ne 1 ]; then
    note_problem "$section" "$file: expected exactly one name: line, found $count"
    return
  fi
  local value
  value=$(fm_value "$fm" name)
  if [ "$value" != "$expected" ]; then
    note_problem "$section" "$file: name: '$value' does not match expected '$expected'"
  fi
}

description_spans_multiple_lines() {
  local fm="$1" mode="$2"
  local desc_line_num fm_line_count next_line
  desc_line_num=$(printf '%s\n' "$fm" | grep -n '^description:' | head -1 | cut -d: -f1)
  fm_line_count=$(printf '%s\n' "$fm" | wc -l)
  if [ "$desc_line_num" -ge "$fm_line_count" ]; then
    return 1
  fi
  next_line=$(printf '%s\n' "$fm" | sed -n "$((desc_line_num + 1))p")
  if [ "$mode" = agent ]; then
    # shellcheck disable=SC2251  # predicate function returns this status; only ever called in an if
    ! [[ "$next_line" =~ ^[A-Za-z_]+: ]]
    return
  fi
  [ -n "$next_line" ] && ! [[ "$next_line" =~ ^[A-Za-z_-]+: ]]
}

check_description_field() {
  local section="$1" file="$2" fm="$3" mode="$4"
  local count
  count=$(fm_count "$fm" description)
  if [ "$count" -ne 1 ]; then
    note_problem "$section" "$file: expected exactly one description: line, found $count"
    return
  fi
  local raw_value
  raw_value=$(fm_value "$fm" description)

  if [ "$mode" = agent ]; then
    if [ -z "$raw_value" ]; then
      note_problem "$section" "$file: description is empty"
      return
    fi
    if description_spans_multiple_lines "$fm" agent; then
      note_problem "$section" "$file: description value spans multiple lines (agents/*.md is generated by sync-codex.sh's single-line extraction, block scalars are rejected there too)"
    fi
    return
  fi

  case "$raw_value" in
  '|' | '|-' | '|+')
    note_problem "$section" "$file: description uses a literal block scalar ($raw_value), does not fold to one line"
    return
    ;;
  '>' | '>-' | '>+')
    return
    ;;
  esac
  if [ -z "$raw_value" ]; then
    note_problem "$section" "$file: description is empty"
    return
  fi
  if description_spans_multiple_lines "$fm" skill; then
    note_problem "$section" "$file: description value spans multiple lines"
  fi
}

check_ai_tell_chars() {
  local section="$1" file="$2" fm="$3"
  local combined
  combined=$(fm_block "$fm" name)$'\n'$(fm_block "$fm" description)
  if printf '%s' "$combined" | grep -qP '[\x{2018}\x{2019}\x{201C}\x{201D}]'; then
    note_problem "$section" "$file: curly quote character in name/description"
  fi
  if printf '%s' "$combined" | grep -qP '\p{So}'; then
    note_problem "$section" "$file: decorative emoji character in name/description"
  fi
}

section_a() {
  echo "== A: skill validity (skills/) =="
  local before=$PROBLEMS
  local checked=0
  local d name file fm
  while IFS= read -r -d '' d; do
    name=$(basename "$d")
    checked=$((checked + 1))
    file="$d/SKILL.md"
    if ! read_frontmatter "$file" fm; then
      note_problem A "$file: $FM_ERROR"
      continue
    fi
    check_name_field A "$file" "$fm" "$name"
    check_description_field A "$file" "$fm" skill
    check_ai_tell_chars A "$file" "$fm"
  done < <(find "$SKILLBOOK/skills" -mindepth 1 -maxdepth 1 -type d ! -name "$SYNCED_SKILLS_DIR" -print0)
  if [ "$PROBLEMS" -eq "$before" ]; then
    echo "ok: $checked skill dirs valid"
  fi
}

section_b() {
  echo "== B: agent validity (agents/) =="
  local before=$PROBLEMS
  local checked=0
  local file base fm
  for file in "$SKILLBOOK"/agents/*.md; do
    [ -f "$file" ] || continue
    checked=$((checked + 1))
    base=$(basename "$file" .md)
    if ! read_frontmatter "$file" fm; then
      note_problem B "$file: $FM_ERROR"
      continue
    fi
    check_name_field B "$file" "$fm" "$base"
    check_description_field B "$file" "$fm" agent
    check_ai_tell_chars B "$file" "$fm"

    local model_count model_value
    model_count=$(fm_count "$fm" model)
    if [ "$model_count" -ne 1 ]; then
      note_problem B "$file: expected exactly one model: line, found $model_count"
    else
      model_value=$(fm_value "$fm" model)
      case "$model_value" in
      haiku | sonnet) ;;
      *) note_problem B "$file: model: '$model_value' is not one of haiku, sonnet" ;;
      esac
    fi

    local codex_model_count codex_model_value
    codex_model_count=$(fm_count "$fm" codex_model)
    if [ "$codex_model_count" -gt 1 ]; then
      note_problem B "$file: expected at most one codex_model: line, found $codex_model_count"
    elif [ "$codex_model_count" -eq 1 ]; then
      codex_model_value=$(fm_value "$fm" codex_model)
      codex_model_supported "$codex_model_value" ||
        note_problem B "$file: codex_model: '$codex_model_value' is not a supported Codex agent model"
    fi

    local reasoning_count reasoning_value
    reasoning_count=$(fm_count "$fm" codex_model_reasoning_effort)
    if [ "$reasoning_count" -gt 1 ]; then
      note_problem B "$file: expected at most one codex_model_reasoning_effort: line, found $reasoning_count"
    elif [ "$reasoning_count" -eq 1 ]; then
      reasoning_value=$(fm_value "$fm" codex_model_reasoning_effort)
      codex_effort_supported "$reasoning_value" ||
        note_problem B "$file: codex_model_reasoning_effort: '$reasoning_value' is not a supported reasoning effort"
    fi

    local cap_count cap_value
    cap_count=$(fm_count "$fm" capability)
    if [ "$cap_count" -ne 1 ]; then
      note_problem B "$file: expected exactly one capability: line, found $cap_count"
    else
      cap_value=$(fm_value "$fm" capability)
      case "$cap_value" in
      read-only | write) ;;
      *) note_problem B "$file: capability: '$cap_value' is not one of read-only, write" ;;
      esac
    fi
  done
  if [ "$PROBLEMS" -eq "$before" ]; then
    echo "ok: $checked agent files valid"
  fi
}

check_symlink_target() {
  local section="$1" link="$2" expected_target="$3"
  if [ ! -e "$link" ] && [ ! -L "$link" ]; then
    note_problem "$section" "$link: missing"
    return 1
  fi
  if [ ! -L "$link" ]; then
    note_problem "$section" "$link: exists but is not a symlink"
    return 1
  fi
  local real expected_real
  real=$(realpath "$link")
  expected_real=$(realpath "$expected_target" 2>/dev/null || echo "$expected_target")
  if [ "$real" != "$expected_real" ]; then
    note_problem "$section" "$link: resolves to $real, expected $expected_real"
    return 1
  fi
  return 0
}

section_c() {
  echo "== C: projection into ~/.claude =="
  local before=$PROBLEMS

  check_symlink_target C "$CLAUDE_HOME/agents" "$SKILLBOOK/agents" || true
  check_symlink_target C "$CLAUDE_HOME/skills" "$SKILLBOOK/skills" || true
  check_symlink_target C "$CLAUDE_HOME/CLAUDE.md" "$SKILLBOOK/GLOBAL-CLAUDE.md" || true

  local checked=0
  local d name resolved real expected_real
  while IFS= read -r -d '' d; do
    name=$(basename "$d")
    checked=$((checked + 1))
    resolved="$CLAUDE_HOME/skills/$name"
    if [ ! -e "$resolved" ]; then
      note_problem C "$resolved: skillbook skill '$name' does not resolve in ~/.claude/skills"
      continue
    fi
    real=$(realpath "$resolved")
    expected_real=$(realpath "$d")
    if [ "$real" != "$expected_real" ]; then
      note_problem C "$resolved: resolves to $real, not skillbook's $expected_real (shadowed)"
    fi
  done < <(find "$SKILLBOOK/skills" -mindepth 1 -maxdepth 1 -type d ! -name "$SYNCED_SKILLS_DIR" -print0)

  if [ -d "$CLAUDE_HOME/skills" ]; then
    local entry
    while IFS= read -r -d '' entry; do
      name=$(basename "$entry")
      [ -f "$SKILLBOOK/skills/$name/SKILL.md" ] && continue
      note_problem C "$entry: present in ~/.claude/skills but not a skillbook skill (shadowing)"
    done < <(find "$CLAUDE_HOME/skills" -mindepth 1 -maxdepth 1 -print0)
  fi

  local file base
  for file in "$SKILLBOOK"/agents/*.md; do
    [ -f "$file" ] || continue
    base=$(basename "$file" .md)
    checked=$((checked + 1))
    resolved="$CLAUDE_HOME/agents/$base.md"
    if [ ! -e "$resolved" ]; then
      note_problem C "$resolved: skillbook agent '$base' does not resolve in ~/.claude/agents"
      continue
    fi
    real=$(realpath "$resolved")
    expected_real=$(realpath "$file")
    if [ "$real" != "$expected_real" ]; then
      note_problem C "$resolved: resolves to $real, not skillbook's $expected_real (shadowed)"
    fi
  done

  if [ -d "$CLAUDE_HOME/agents" ]; then
    while IFS= read -r -d '' entry; do
      name=$(basename "$entry" .md)
      [ -f "$SKILLBOOK/agents/$name.md" ] && continue
      note_problem C "$entry: present in ~/.claude/agents but not a skillbook agent (shadowing)"
    done < <(find "$CLAUDE_HOME/agents" -mindepth 1 -maxdepth 1 -print0)
  fi

  if [ "$PROBLEMS" -eq "$before" ]; then
    echo "ok: $checked skills+agents plus CLAUDE.md resolve to skillbook, no shadowing"
  fi
}

regenerate_agent_toml() {
  local name="$1"
  local file="$SKILLBOOK/agents/$name.md"
  local fm
  read_frontmatter "$file" fm || return 1

  local description model_raw codex_model codex_model_reasoning_effort capability
  description=$(fm_value "$fm" description)
  model_raw=$(fm_value "$fm" model)
  codex_model=$(fm_value "$fm" codex_model)
  codex_model_reasoning_effort=$(fm_value "$fm" codex_model_reasoning_effort)
  capability=$(fm_value "$fm" capability)

  if [ -z "$description" ] || description_spans_multiple_lines "$fm" agent; then
    return 1
  fi

  local model
  model=$(codex_model_for_claude_model "$model_raw") || return 1
  if [ -n "$codex_model" ]; then
    model="$codex_model"
  fi
  model=$(codex_resolve_model "$model") || return 1

  local sandbox_mode
  case "$capability" in
  read-only) sandbox_mode=read-only ;;
  write) sandbox_mode=workspace-write ;;
  *) return 1 ;;
  esac

  local body
  body=$(tail -n "+$((FM_SECOND_DASH + 1))" "$file")
  case "$body" in
  *"'''"*) return 1 ;;
  esac

  local esc_description
  esc_description=$(printf '%s' "$description" | sed 's/\\/\\\\/g; s/"/\\"/g')

  printf '# generated by skillbook/scripts/sync-codex.sh from agents/%s.md — do not edit\n' "$name"
  printf 'name = "%s"\n' "$name"
  printf 'description = "%s"\n' "$esc_description"
  printf 'model = "%s"\n' "$model"
  if [ -n "$codex_model_reasoning_effort" ]; then
    printf 'model_reasoning_effort = "%s"\n' "$codex_model_reasoning_effort"
  fi
  printf 'sandbox_mode = "%s"\n' "$sandbox_mode"
  printf "developer_instructions = '''\n"
  printf '%s\n' "$body"
  printf "'''\n"
}

codex_home_never_synced() {
  local p
  for p in "$CODEX_HOME/AGENTS.md" "$CODEX_HOME/hooks.json" \
           "$CODEX_HOME/agents/bolt.toml" "$CODEX_HOME/agents/hand-do.toml" "$CODEX_HOME/agents/hand-ex.toml"; do
    { [ -e "$p" ] || [ -L "$p" ]; } && return 1
  done

  if [ -d "$CODEX_HOME/skills" ]; then
    local entry target
    while IFS= read -r -d '' entry; do
      [ -L "$entry" ] || continue
      target=$(readlink "$entry")
      case "$target" in
        "$SKILLBOOK/skills/"*) return 1 ;;
      esac
    done < <(find "$CODEX_HOME/skills" -mindepth 1 -maxdepth 1 -print0)
  fi

  return 0
}

section_d() {
  echo "== D: projection into ~/.codex =="
  if [ ! -d "$CODEX_HOME" ]; then
    # shellcheck disable=SC2088  # ~ is prose here, the real path follows from $CODEX_HOME
    echo "~/.codex ($CODEX_HOME) does not exist, skipping"
    return
  fi
  if codex_home_never_synced; then
    echo "warn: ~/.codex present but never synced — run scripts/sync-codex.sh"
    return
  fi
  local before=$PROBLEMS

  local d name link target
  local checked_skills=0
  while IFS= read -r -d '' d; do
    name=$(basename "$d")
    checked_skills=$((checked_skills + 1))
    link="$CODEX_HOME/skills/$name"
    if [ ! -L "$link" ]; then
      note_problem D "$link: missing symlink for skill $name"
      continue
    fi
    target=$(readlink "$link")
    if [ "$target" != "$SKILLBOOK/skills/$name/" ]; then
      note_problem D "$link: symlink target '$target' does not match skills/$name/"
    fi
  done < <(find "$SKILLBOOK/skills" -mindepth 1 -maxdepth 1 -type d ! -name "$SYNCED_SKILLS_DIR" -print0)

  local tmp
  for name in bolt hand-do hand-ex; do
    local toml="$CODEX_HOME/agents/$name.toml"
    tmp=$(mktemp)
    if ! regenerate_agent_toml "$name" >"$tmp"; then
      note_problem D "agents/$name.md: cannot regenerate expected TOML (invalid frontmatter, see section B)"
      rm -f "$tmp"
      continue
    fi
    if [ ! -f "$toml" ]; then
      note_problem D "$toml: missing, run scripts/sync-codex.sh"
    elif ! cmp -s "$tmp" "$toml"; then
      note_problem D "$toml: stale, does not match agents/$name.md (run scripts/sync-codex.sh)"
    fi
    rm -f "$tmp"
  done

  local marker
  marker=$(sed -n "s/^MARKER='\(.*\)'\$/\1/p" "$SKILLBOOK/scripts/sync-codex.sh")
  local agents_target="$CODEX_HOME/AGENTS.md"
  if [ ! -f "$agents_target" ]; then
    note_problem D "$agents_target: missing, run scripts/sync-codex.sh"
  else
    local first_line
    first_line=$(sed -n '1p' "$agents_target")
    if [ "$first_line" != "$marker" ]; then
      note_problem D "$agents_target: does not carry the generated marker"
    else
      tmp=$(mktemp)
      {
        printf '%s\n' "$marker"
        printf '\n'
        cat "$SKILLBOOK/GLOBAL-CORE.md"
        printf '\n'
        cat "$SKILLBOOK/CODEX-TAIL.md"
      } >"$tmp"
      if ! cmp -s "$tmp" "$agents_target"; then
        note_problem D "$agents_target: stale, does not match GLOBAL-CORE.md + CODEX-TAIL.md (run scripts/sync-codex.sh)"
      fi
      rm -f "$tmp"
    fi
  fi

  local hooks_target="$CODEX_HOME/hooks.json"
  local hooks_desired="$SKILLBOOK/codex/hooks.json"
  if [ ! -L "$hooks_target" ]; then
    note_problem D "$hooks_target: missing or not a symlink"
  else
    local hooks_current
    hooks_current=$(readlink "$hooks_target")
    if [ "$hooks_current" != "$hooks_desired" ]; then
      note_problem D "$hooks_target: symlink target '$hooks_current' does not match $hooks_desired"
    fi
  fi

  if [ "$PROBLEMS" -eq "$before" ]; then
    echo "ok: $checked_skills skill symlinks, 3 agent tomls, AGENTS.md and hooks.json all fresh"
  fi
}

section_e() {
  echo "== E: MCP servers in ~/.claude.json =="
  if ! command -v jq >/dev/null 2>&1; then
    note_problem E "jq missing"
    return
  fi
  local before=$PROBLEMS
  local out rc=0
  out=$(bash "$SKILLBOOK/scripts/sync-mcp.sh" --dry-run 2>&1) || rc=$?
  if [ "$rc" -ne 0 ]; then
    note_problem E "sync-mcp.sh --dry-run failed: $(printf '%s' "$out" | tr '\n' ' ')"
    return
  fi
  local line
  while IFS= read -r line; do
    [ -n "$line" ] || continue
    note_problem E "$line (run scripts/sync-mcp.sh)"
  done <<<"$out"
  if [ "$PROBLEMS" -eq "$before" ]; then
    echo "ok: MCP servers match mcp/servers.json"
  fi
}

section_f() {
  echo "== F: per-project skill additions (skills/*/projects/) =="
  local before=$PROBLEMS
  local projects_root="${PROJECTS_ROOT:-$HOME/Projects}"
  local checked=0
  local d name file repo fm
  while IFS= read -r -d '' d; do
    name=$(basename "$d")
    [ -d "$d/projects" ] || continue
    checked=$((checked + 1))
    if ! grep -qE "^!\`[^\`]*/scripts/skill-project\.sh $name\`\$" "$d/SKILL.md"; then
      note_problem F "$d/SKILL.md: has a projects/ dir but no !\`...skill-project.sh $name\` line, those files never load"
    elif ! read_frontmatter "$d/SKILL.md" fm || ! printf '%s\n' "$fm" | grep -q '^allowed-tools:.*Bash(\*/skill-project\.sh \*)'; then
      note_problem F "$d/SKILL.md: frontmatter lacks allowed-tools: Bash(*/skill-project.sh *), the load-time command is denied in non-interactive runs"
    fi
    for file in "$d"/projects/*.md; do
      [ -f "$file" ] || continue
      repo=$(basename "$file" .md)
      known_project_key "$repo" || echo "info: skills/$name/projects/$repo.md matches no dir under $projects_root and no scope in hooks/scope-map.sh"
    done
  done < <(find "$SKILLBOOK/skills" -mindepth 1 -maxdepth 1 -type d ! -name "$SYNCED_SKILLS_DIR" -print0)
  if [ "$PROBLEMS" -eq "$before" ]; then
    echo "ok: $checked skills with projects/ load them"
  fi
}

check_testing_md() {
  local file="$1" label="$2"

  grep -q '^base: *[^ ]' "$file" || note_problem G "$label: no base: line"

  awk '
    /^\[.+\]$/ { if (open && f && u) good = 1; open = 1; f = 0; u = 0; next }
    /^focused:/ { f = 1 }
    /^full:/ { u = 1 }
    END { if (open && f && u) good = 1; exit good ? 0 : 1 }
  ' "$file" || note_problem G "$label: no [repo] section with both focused: and full:"
}

section_g() {
  echo "== G: per-project agent additions (agent-projects/) =="
  local before=$PROBLEMS
  local projects_root="${PROJECTS_ROOT:-$HOME/Projects}"
  local checked=0
  local d key file agent

  if ! jq -e '[.hooks.SubagentStart[]?.hooks[]?.command] | any(contains("load-agent-additions.sh"))' "$SKILLBOOK/settings.json" >/dev/null 2>&1; then
    note_problem G "settings.json: SubagentStart does not register hooks/load-agent-additions.sh, agent additions never load"
  fi
  [ -f "$SKILLBOOK/hooks/load-agent-additions.sh" ] || note_problem G "hooks/load-agent-additions.sh: missing"

  for d in "$SKILLBOOK"/agent-projects/*/; do
    [ -d "$d" ] || continue
    key=$(basename "$d")
    known_project_key "$key" || echo "info: agent-projects/$key/ matches no dir under $projects_root and no scope in hooks/scope-map.sh"
    for file in "$d"*.md; do
      [ -f "$file" ] || continue
      checked=$((checked + 1))
      agent=$(basename "$file" .md)
      if [ "$agent" = "testing" ]; then
        check_testing_md "$file" "agent-projects/$key/testing.md"
        continue
      fi
      [ -f "$SKILLBOOK/agents/$agent.md" ] || note_problem G "agent-projects/$key/$agent.md: no agents/$agent.md, the addition never loads"
    done
  done

  if [ "$PROBLEMS" -eq "$before" ]; then
    echo "ok: $checked agent additions name real agents and the hook is registered"
  fi
}

section_a
section_b
section_c
section_d
section_e
section_f
section_g

echo "== summary =="
if [ "$PROBLEMS" -eq 0 ]; then
  echo "ok: no drift found"
  exit 0
fi
echo "$PROBLEMS problem(s) found, see FAIL lines above"
exit 1
